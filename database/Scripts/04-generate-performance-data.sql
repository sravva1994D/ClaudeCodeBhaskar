/*
  04-generate-performance-data.sql
  Adds seed-performance data to the DEVELOPMENT database for the browser timing checks
  (Documentation/04-Implementation/16-Module-8-Plan.md; D-M8-1, D-M8-2; NFR-PRF-001, NFR-PRF-002, SC-002, NFR-SCL-001).

  Adds 1,000 synthetic patients, about 5,000 visits (some with vitals and prescriptions) and 2,000 appointments.
  Synthetic data only, never clinical. Marked rows: patients named "Test Patient nnnn" with an e-mail on
  example.test. Remove them all with 05-remove-performance-data.sql.

  The script stops unless the database is PatientManagement, and stops if marked patients already exist.
  It runs in one transaction: if any insert fails (for example, an appointment clashes with a real slot),
  nothing is kept.

  Run:
    sqlcmd -S <your-instance> -E -b -i database/Scripts/04-generate-performance-data.sql -d PatientManagement
*/

SET QUOTED_IDENTIFIER ON;  -- required by MERGE and by the filtered index on Appointments
SET XACT_ABORT ON;
SET NOCOUNT ON;

IF DB_NAME() <> N'PatientManagement'
BEGIN
    THROW 50000, N'This script only runs against the PatientManagement development database.', 1;
END

IF EXISTS (SELECT 1 FROM [Patients] WHERE [Email] LIKE N'%@example.test')
BEGIN
    THROW 50001, N'Synthetic performance patients already exist. Run 05-remove-performance-data.sql first.', 1;
END

CREATE TABLE #Numbers ([n] int NOT NULL PRIMARY KEY);
INSERT INTO #Numbers ([n])
SELECT TOP (2000) ROW_NUMBER() OVER (ORDER BY (SELECT NULL))
FROM sys.all_objects AS a CROSS JOIN sys.all_objects AS b;

BEGIN TRANSACTION;

-- 1,000 patients. The identity is generated by the table; PatientCode is a computed column.
DECLARE @PatientMap TABLE ([PatientId] int NOT NULL, [PatientNo] int NOT NULL);

MERGE [Patients] AS target
USING (SELECT [n] AS [PatientNo] FROM #Numbers WHERE [n] <= 1000) AS src
ON 1 = 0
WHEN NOT MATCHED THEN
    INSERT ([FullName], [DateOfBirth], [Gender], [Phone], [Email], [Address])
    VALUES (
        CONCAT(N'Test Patient ', RIGHT(N'0000' + CAST(src.[PatientNo] AS nvarchar(4)), 4), N' ',
               CHOOSE(1 + src.[PatientNo] % 10, N'Anderson', N'Brown', N'Clark', N'Davis', N'Evans',
                                                N'Foster', N'Green', N'Harris', N'Ibrahim', N'Jones')),
        DATEADD(DAY, (src.[PatientNo] * 37) % 20000, CAST(N'1950-01-01' AS date)),
        CHOOSE(1 + src.[PatientNo] % 3, N'Male', N'Female', N'Other'),
        CONCAT(N'55', RIGHT(N'00000000' + CAST(src.[PatientNo] AS nvarchar(8)), 8)),
        CONCAT(N'test.patient', src.[PatientNo], N'@example.test'),
        CONCAT(N'Test address ', src.[PatientNo]))
OUTPUT inserted.[Id], src.[PatientNo] INTO @PatientMap ([PatientId], [PatientNo]);

-- Visits: 0 to 10 per patient, about 5 on average, spread over the last 365 days.
DECLARE @Visits TABLE ([ConsultationId] int NOT NULL, [PatientNo] int NOT NULL, [VisitNo] int NOT NULL,
                       [PatientId] int NOT NULL, [VisitDateTime] datetime2(0) NOT NULL);

MERGE [Consultations] AS target
USING (
    SELECT pm.[PatientId], pm.[PatientNo], v.[n] AS [VisitNo],
           DATEADD(MINUTE, 30 * ((pm.[PatientNo] + v.[n]) % 16),
               DATEADD(HOUR, 9,
                   DATEADD(DAY, -((pm.[PatientNo] * 31 + v.[n] * 53) % 365),
                       CAST(CAST(SYSDATETIME() AS date) AS datetime2(0))))) AS [VisitDateTime]
    FROM @PatientMap AS pm
    INNER JOIN #Numbers AS v ON v.[n] <= (pm.[PatientNo] * 7) % 11
) AS src
ON 1 = 0
WHEN NOT MATCHED THEN
    INSERT ([PatientId], [AppointmentId], [VisitDateTime], [Complaints], [Diagnosis], [FinishedAt])
    VALUES (src.[PatientId], NULL, src.[VisitDateTime],
            CONCAT(N'Synthetic complaint ', src.[PatientNo], N'-', src.[VisitNo]),
            CONCAT(N'Synthetic diagnosis ', src.[PatientNo], N'-', src.[VisitNo]),
            src.[VisitDateTime])
OUTPUT inserted.[Id], src.[PatientNo], src.[VisitNo], src.[PatientId], src.[VisitDateTime]
INTO @Visits ([ConsultationId], [PatientNo], [VisitNo], [PatientId], [VisitDateTime]);

-- Vitals for about 4 in 5 visits. All values inside the BRD ranges (PDR-19).
INSERT INTO [VitalSigns] ([ConsultationId], [TemperatureC], [SystolicMmHg], [DiastolicMmHg], [PulseBpm])
SELECT vis.[ConsultationId],
       CAST(36.0 + ((vis.[PatientNo] + vis.[VisitNo]) % 10) / 10.0 AS decimal(4, 1)),
       CAST(110 + (vis.[PatientNo] + vis.[VisitNo]) % 30 AS smallint),
       CAST(70 + (vis.[PatientNo] * vis.[VisitNo]) % 20 AS smallint),
       CAST(60 + (vis.[PatientNo] + 3 * vis.[VisitNo]) % 40 AS smallint)
FROM @Visits AS vis
WHERE (vis.[PatientNo] + vis.[VisitNo]) % 5 <> 0;

-- Prescriptions (unprinted) for about half of the visits, with one or two medicines each.
DECLARE @Prescriptions TABLE ([PrescriptionId] int NOT NULL, [ConsultationId] int NOT NULL,
                              [PatientNo] int NOT NULL, [VisitNo] int NOT NULL);

MERGE [Prescriptions] AS target
USING (SELECT vis.[ConsultationId], vis.[PatientNo], vis.[VisitNo]
       FROM @Visits AS vis
       WHERE (vis.[PatientNo] + vis.[VisitNo]) % 2 = 0) AS src
ON 1 = 0
WHEN NOT MATCHED THEN
    INSERT ([ConsultationId], [IsPrinted], [PrintedAt])
    VALUES (src.[ConsultationId], 0, NULL)
OUTPUT inserted.[Id], src.[ConsultationId], src.[PatientNo], src.[VisitNo]
INTO @Prescriptions ([PrescriptionId], [ConsultationId], [PatientNo], [VisitNo]);

INSERT INTO [PrescriptionItems] ([PrescriptionId], [Name], [Dosage], [Frequency], [Duration], [Instructions], [SortOrder])
SELECT rx.[PrescriptionId],
       CHOOSE(1 + (rx.[PatientNo] + rx.[VisitNo]) % 5, N'Paracetamol', N'Amoxicillin', N'Cetirizine', N'Ibuprofen', N'Omeprazole'),
       N'500 mg', N'Twice a day', N'5 days', NULL, CAST(1 AS smallint)
FROM @Prescriptions AS rx
UNION ALL
SELECT rx.[PrescriptionId],
       CHOOSE(1 + (rx.[PatientNo] + rx.[VisitNo] + 2) % 5, N'Paracetamol', N'Amoxicillin', N'Cetirizine', N'Ibuprofen', N'Omeprazole'),
       N'250 mg', N'Once a day', N'3 days', N'After food', CAST(2 AS smallint)
FROM @Prescriptions AS rx
WHERE rx.[PatientNo] % 3 = 0;

-- 2,000 appointments: 14 half-hour slots a day (09:00 to 13:00 and 17:00 to 20:00, PDR-06), on
-- alternate days from 180 days ago to about 104 days ahead. Each slot is used once, so the
-- unique slot index is respected. Past appointments are Cancelled or No-show (they do not hold a slot).
MERGE [Appointments] AS target
USING (
    SELECT slots.[PatientId], slots.[StartTime],
           CASE WHEN CAST(slots.[StartTime] AS date) < CAST(SYSDATETIME() AS date)
                THEN CASE WHEN slots.[n] % 2 = 0 THEN N'No-show' ELSE N'Cancelled' END
                ELSE N'Scheduled' END AS [Status]
    FROM (
        SELECT pm.[PatientId], a.[n],
               DATEADD(MINUTE,
                       CASE WHEN (a.[n] - 1) % 14 < 8
                            THEN 540 + 30 * ((a.[n] - 1) % 14)
                            ELSE 1020 + 30 * ((a.[n] - 1) % 14 - 8) END,
                       DATEADD(DAY, -180 + 2 * ((a.[n] - 1) / 14),
                               CAST(CAST(SYSDATETIME() AS date) AS datetime2(0)))) AS [StartTime]
        FROM #Numbers AS a
        INNER JOIN @PatientMap AS pm ON pm.[PatientNo] = (a.[n] * 13) % 1000 + 1
        WHERE a.[n] <= 2000
    ) AS slots
) AS src
ON 1 = 0
WHEN NOT MATCHED THEN
    INSERT ([PatientId], [StartTime], [DurationMinutes], [Status], [IsArchived])
    VALUES (src.[PatientId], src.[StartTime], 30, src.[Status], 0);

COMMIT TRANSACTION;

DROP TABLE #Numbers;

-- Counts for the review package (no names, phones or addresses are printed).
SELECT
    (SELECT COUNT(*) FROM [Patients] WHERE [Email] LIKE N'%@example.test')                                  AS [SyntheticPatients],
    (SELECT COUNT(*) FROM [Consultations] AS c INNER JOIN [Patients] AS p ON p.[Id] = c.[PatientId]
        WHERE p.[Email] LIKE N'%@example.test')                                                             AS [SyntheticVisits],
    (SELECT COUNT(*) FROM [VitalSigns] AS v INNER JOIN [Consultations] AS c ON c.[Id] = v.[ConsultationId]
        INNER JOIN [Patients] AS p ON p.[Id] = c.[PatientId] WHERE p.[Email] LIKE N'%@example.test')         AS [SyntheticVitals],
    (SELECT COUNT(*) FROM [Prescriptions] AS r INNER JOIN [Consultations] AS c ON c.[Id] = r.[ConsultationId]
        INNER JOIN [Patients] AS p ON p.[Id] = c.[PatientId] WHERE p.[Email] LIKE N'%@example.test')         AS [SyntheticPrescriptions],
    (SELECT COUNT(*) FROM [Appointments] AS a INNER JOIN [Patients] AS p ON p.[Id] = a.[PatientId]
        WHERE p.[Email] LIKE N'%@example.test')                                                             AS [SyntheticAppointments];
GO
